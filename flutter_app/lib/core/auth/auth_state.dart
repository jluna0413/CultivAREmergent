/// NOTE:
/// The Riverpod provider is generated by `build_runner` as `authProvider`.
/// Remove manual provider definitions to avoid symbol collisions with generated code.
///
/// Convenience provider for current User? (null when unauthenticated)
final currentUserProvider = Provider<User?>((ref) {
  // Use the generated provider name `authProvider` produced by riverpod_generator
  final authState = ref.watch(authProvider);
  return authState.when(
    authenticated: (user) => user,
    unauthenticated: () => null,
    loading: () => null,
  );
});
