/// Freezed-based AuthState union: Authenticated, Unauthenticated, Loading
@freezed
abstract class AuthState with _$AuthState {
  const factory AuthState.authenticated(User user) = Authenticated;
  const factory AuthState.unauthenticated() = Unauthenticated;
  const factory AuthState.loading() = Loading;
}

/// OAuthRepository singleton provider for Keycloak authentication
final authRepositoryProvider = Provider<OAuthRepository>((ref) {
  return getOAuthRepository();
});

